function normalizeStr(s) {
  return String(s||'').toLowerCase().replace(/apotik/g,'apotek').replace(/[^a-z0-9]/g,'');
}

/**
 * Detect ORA customer
 */
function isOraCustomer(custName, jenis) {
  var u = String(custName||'').toUpperCase();
  var j = String(jenis||'').toUpperCase();
  return j==='ORA' || u.indexOf('HELIOS')!==-1 || u.indexOf('HAK')===0 || u==='1001';
}

/**
 * Full categorization — same logic as parser.ts categorize()
 */
function categorizeCustomer(jenisTransaksi, custName, shipToSite, billToSite) {
  var u = String(custName||'').trim().toUpperCase();
  var jenis = String(jenisTransaksi||'').toUpperCase();

  // 1P: ORA or 1P DOO customers
  if (jenis==='ORA' || u.indexOf('HELIOS')!==-1 || u.indexOf('HAK')===0 || u==='1001' ||
      u.indexOf('HALOMEDIKA')!==-1 || u.indexOf('MEDIKA PRIMA')!==-1 ||
      u.indexOf('SBS')!==-1 || u.indexOf('PASTI HEMAT')!==-1 || u.indexOf('MEDIKA AKSES')!==-1) {
    return '1P';
  }

  var codes = get2PCodeSet();
  // 2P: check ship-to site code
  if (shipToSite) {
    var num = String(shipToSite).replace(/[^0-9]/g,'').replace(/^0+/,'');
    if (num && codes[num]) return '2P';
  }
  // 2P: check bill-to site code
  if (billToSite) {
    var num2 = String(billToSite).replace(/[^0-9]/g,'').replace(/^0+/,'');
    if (num2 && codes[num2]) return '2P';
  }

  // 2P: check normalized name
  var normCust = normalizeStr(custName);
  var names = get2PNameSet();
  if (names[normCust]) return '2P';

  // masterApotek exact match
  var apotek = _MAPOTEK[String(custName||'').toLowerCase()] || _MAPOTEK[normCust];
  if (apotek==='1P'||apotek==='2P'||apotek==='3P') return apotek;

  return '3P';
}

/**
 * Get product category from item code
 */
function getProductCategory(itemCode) {
  if (!itemCode) return '';
  var clean = String(itemCode).trim();
  return _MPROD[clean] || _MPROD[clean.replace(/[^0-9]/g,'')] || '';
}

