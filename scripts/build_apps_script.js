// ── Helper: normalize (same as parser.ts) ─────────────────────────────────────
function normalize(s) {
  return String(s || '').toLowerCase().replace(/apotik/g, 'apotek').replace(/[^a-z0-9]/g, '');
}

// ── 1. Build compact master lookups ───────────────────────────────────────────
const master2P = JSON.parse(fs.readFileSync(path.join(libDir, 'master2P.json'), 'utf8'));
const codes2P = new Set();
const names2P = new Set();
master2P.forEach(item => {
  if (item.codeNum) codes2P.add(item.codeNum);
  if (item.kodeCustomer) {
    const num = item.kodeCustomer.replace(/[^0-9]/g, '').replace(/^0+/, '');
    if (num) codes2P.add(num);
  }
  if (item.namaApotekMBI) names2P.add(normalize(item.namaApotekMBI));
  if (item.namaMerchant) names2P.add(normalize(item.namaMerchant));
});

const masterApotek = JSON.parse(fs.readFileSync(path.join(libDir, 'masterApotek.json'), 'utf8'));
const apotekMap = {};
for (const [k, v] of Object.entries(masterApotek)) {
  apotekMap[normalize(k)] = v;
}

const masterProduct = JSON.parse(fs.readFileSync(path.join(libDir, 'masterProduct.json'), 'utf8'));
const prodCodeMap = {};
masterProduct.forEach(p => {
  const cat = String(p.kategori || '').trim().toUpperCase();
  if (!cat) return;
  [p.kodeBarang, p.kodeOracle, p.kodeAccurate].filter(Boolean).forEach(c => {
    const clean = String(c).trim();
    if (clean) {
      prodCodeMap[clean] = cat;
      const numOnly = clean.replace(/[^0-9]/g, '');
      if (numOnly) prodCodeMap[numOnly] = cat;
    }
  });
});

const masterPrekOOT = JSON.parse(fs.readFileSync(path.join(libDir, 'masterPrekursorOOT.json'), 'utf8'));
const prekOOTMap = {};
masterPrekOOT.forEach(p => {
  const cat = String(p.klasifikasi || p.kategori || '').trim();
  if (!cat) return;
  if (p.namaBarang) prekOOTMap[normalize(p.namaBarang)] = cat;
  if (p.kodeBarang) prekOOTMap[String(p.kodeBarang).trim()] = cat;
});

