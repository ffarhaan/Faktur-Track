/**
 * Generates compact lookup data from master JSON files
 * Output: scripts/masterCompact.js (embeddable in Apps Script)
 */
const fs = require('fs');
const path = require('path');

const libDir = path.join(__dirname, '..', 'lib');
const outFile = path.join(__dirname, 'masterCompact.js');

// ── Helper normalize (same as parser.ts) ──────────────────────────────────────
function normalize(s) {
  return String(s || '').toLowerCase().replace(/apotik/g, 'apotek').replace(/[^a-z0-9]/g, '');
}

// ── 1. master2P → Set of codeNums + Set of normalized names ──────────────────
const master2P = JSON.parse(fs.readFileSync(path.join(libDir, 'master2P.json'), 'utf8'));
const codes2P = new Set();
const names2P = new Set();
master2P.forEach(item => {
  if (item.codeNum) codes2P.add(item.codeNum);
  if (item.kodeCustomer) {
    const num = item.kodeCustomer.replace(/[^0-9]/g, '').replace(/^0+/, '');
    if (num) codes2P.add(num);
  }
  if (item.namaApotekMBI) names2P.add(normalize(item.namaApotekMBI));
  if (item.namaMerchant) names2P.add(normalize(item.namaMerchant));
});
console.log(`master2P: ${codes2P.size} codes, ${names2P.size} names`);

// ── 2. masterApotek → Map of normalized name → category ──────────────────────
const masterApotek = JSON.parse(fs.readFileSync(path.join(libDir, 'masterApotek.json'), 'utf8'));
const apotekMap = {};
for (const [k, v] of Object.entries(masterApotek)) {
  apotekMap[normalize(k)] = v;
}
console.log(`masterApotek: ${Object.keys(apotekMap).length} entries`);

// ── 3. masterProduct → compact code→cat + compact name→cat ───────────────────
const masterProduct = JSON.parse(fs.readFileSync(path.join(libDir, 'masterProduct.json'), 'utf8'));
const prodCodeMap = {}; // code → kategori
const prodNameMap = {}; // normalized name → kategori
masterProduct.forEach(p => {
  const cat = String(p.kategori || '').trim().toUpperCase();
  if (!cat) return;
  [p.kodeBarang, p.kodeOracle, p.kodeAccurate].filter(Boolean).forEach(c => {
    const clean = String(c).trim();
    if (clean) {
      prodCodeMap[clean] = cat;
      const numOnly = clean.replace(/[^0-9]/g, '');
      if (numOnly) prodCodeMap[numOnly] = cat;
    }
  });
  if (p.namaBarang) {
    const norm = normalize(p.namaBarang);
    if (norm.length >= 8) prodNameMap[norm] = cat;
  }
});
console.log(`masterProduct: ${Object.keys(prodCodeMap).length} codes, ${Object.keys(prodNameMap).length} names`);

// ── 4. masterPrekursorOOT → Set of normalized names ──────────────────────────
const masterPrekOOT = JSON.parse(fs.readFileSync(path.join(libDir, 'masterPrekursorOOT.json'), 'utf8'));
const prekOOTMap = {}; // normalized name → 'Prekursor' | 'OOT'
masterPrekOOT.forEach(p => {
  const cat = String(p.klasifikasi || p.kategori || '').trim();
  if (!cat) return;
  if (p.namaBarang) prekOOTMap[normalize(p.namaBarang)] = cat;
  if (p.kodeBarang) prekOOTMap[String(p.kodeBarang).trim()] = cat;
});
console.log(`masterPrekursorOOT: ${Object.keys(prekOOTMap).length} entries`);

// ── Write output ──────────────────────────────────────────────────────────────
const output = `// AUTO-GENERATED by scripts/generate_master_compact.js
// Do not edit manually - run: node scripts/generate_master_compact.js

var MASTER_2P_CODES = ${JSON.stringify([...codes2P])};
var MASTER_2P_NAMES = ${JSON.stringify([...names2P])};
var MASTER_APOTEK = ${JSON.stringify(apotekMap)};
var MASTER_PROD_CODE = ${JSON.stringify(prodCodeMap)};
var MASTER_PREK_OOT = ${JSON.stringify(prekOOTMap)};
`;

fs.writeFileSync(outFile, output, 'utf8');
const sizeKB = (fs.statSync(outFile).size / 1024).toFixed(1);
console.log(`\n✅ Output: scripts/masterCompact.js (${sizeKB} KB)`);
